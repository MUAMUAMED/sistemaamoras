// Integração real em um PostgreSQL local isolado. Nunca executa no banco da loja.
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const express = require('express');
const jwt = require('jsonwebtoken');
const dbUrl = new URL(process.env.DATABASE_URL || 'postgresql://stockqa@127.0.0.1:55439/postgres');
if (dbUrl.hostname !== '127.0.0.1' || dbUrl.port !== '55439') throw new Error('Teste permitido somente no PostgreSQL de QA, porta 55439.');
process.env.DATABASE_URL = dbUrl.toString();
process.env.JWT_SECRET = 'mobile-stock-local-integration-test';
process.env.IMAGE_EMBEDDING_PROVIDER = 'openrouter';
const { prisma } = require('../dist/config/database');
const { ensureMobileStockSetup } = require('../dist/services/mobile-stock-setup');
const router = require('../dist/routes/mobile-stock.routes').default;
const nativeFetch = global.fetch;
let server;
let passed = 0;
async function main() {
  await require('node:fs/promises').mkdir('uploads/products', { recursive: true });
  await ensureMobileStockSetup(); await ensureMobileStockSetup();
  await prisma.inventorySession.deleteMany(); await prisma.stockOperation.deleteMany(); await prisma.stockMovement.deleteMany();
  await prisma.productImage.deleteMany(); await prisma.product.deleteMany(); await prisma.user.deleteMany();
  const user = await prisma.user.create({ data: { email: 'stockqa@example.invalid', name: 'QA', password: 'unused' } });
  const other = await prisma.user.create({ data: { email: 'stockqa2@example.invalid', name: 'QA 2', password: 'unused' } });
  const token = jwt.sign({ userId: user.id }, process.env.JWT_SECRET);
  const otherToken = jwt.sign({ userId: other.id }, process.env.JWT_SECRET);
  const app = express(); app.use(express.json()); app.use('/api/mobile-stock', router);
  app.use((err, req, res, next) => { console.error(err.message); res.status(500).json({ error: err.message }); });
  server = app.listen(0, '127.0.0.1'); await new Promise((resolve) => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}/api/mobile-stock`;
  async function call(path, body, status = 200, access = token) {
    const r = await nativeFetch(base + path, { method: body ? 'POST' : 'GET', headers: { Authorization: 'Bearer ' + access, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
    const j = await r.json(); assert.equal(r.status, status, JSON.stringify(j)); return j;
  }
  function pass(name) { passed++; console.log(`OK ${passed}: ${name}`); }
  const create = (name, loja, armazem) => prisma.product.create({ data: { name, stockLoja: loja, stockArmazem: armazem, stock: loja + armazem, barcode: randomUUID(), status: 'ATIVO' } });
  const a = await create('Vestido A', 5, 7); const b = await create('Blusa B', 3, 4);
  const warehouse = await create('Só armazém', 0, 10);
  const draft = await prisma.product.create({ data: { name: 'Rascunho', stockLoja: 7, stock: 7, isDraft: true } });
  await call('/inventory/active', undefined, 401, 'invalid'); pass('autenticação obrigatória');
  const session = await call('/inventory', {}, 201); assert.equal(session.items.length, 2);
  assert.equal((await call('/inventory', {}, 201)).id, session.id);
  await call('/inventory', {}, 409, otherToken); await call(`/inventory/${session.id}`, undefined, 404, otherToken);
  pass('snapshot só da loja, retomada persistente e isolamento por usuário');
  const scan = { code: a.barcode, quantity: 2, mode: 'ADD', requestId: randomUUID() };
  await call(`/inventory/${session.id}/count`, scan); await call(`/inventory/${session.id}/count`, scan);
  let details = await call(`/inventory/${session.id}`); assert.equal(details.items.find((i) => i.productId === a.id).countedQuantity, 2);
  await call(`/inventory/${session.id}/count`, { ...scan, quantity: 1 }, 409);
  await call(`/inventory/${session.id}/count`, { ...scan, quantity: 0, requestId: randomUUID() }, 400);
  await call(`/inventory/${session.id}/count`, { code: 'unknown', quantity: 1, requestId: randomUUID() }, 404);
  pass('reenvio da leitura não duplica, valida quantidade e etiqueta desconhecida');
  const review = await call(`/inventory/${session.id}/review`); assert.equal(review.summary.missing, 6);
  const final = await call(`/inventory/${session.id}/finalize`, { reviewToken: review.reviewToken }); assert.equal(final.missing, 6);
  assert.deepEqual(await call(`/inventory/${session.id}/finalize`, { reviewToken: review.reviewToken }), final);
  const afterA = await prisma.product.findUnique({ where: { id: a.id } }); const afterB = await prisma.product.findUnique({ where: { id: b.id } });
  assert.equal(afterA.stockLoja, 2); assert.equal(afterA.stockArmazem, 7); assert.equal(afterA.stock, 9);
  assert.equal(afterB.stockLoja, 0); assert.equal(afterB.stockArmazem, 4); assert.equal(afterB.stock, 4);
  assert.equal(await prisma.stockMovement.count({ where: { reference: session.id } }), 2);
  assert.equal((await prisma.product.findUnique({ where: { id: warehouse.id } })).stock, 10);
  assert.equal((await prisma.product.findUnique({ where: { id: draft.id } })).stock, 7);
  pass('baixa automática parcial e de não lidas, preserva armazém e não repete histórico');
  const op = { productId: a.id, location: 'LOJA', delta: 3, reason: 'Teste', requestId: randomUUID() };
  const adjusted = await call('/restock/adjust', op); assert.equal(adjusted.product.stockLoja, 5); assert.equal(adjusted.product.stock, 12);
  await call('/restock/adjust', op); assert.equal((await prisma.product.findUnique({ where: { id: a.id } })).stockLoja, 5);
  await call('/restock/adjust', { ...op, delta: -99, requestId: randomUUID() }, 409);
  await call('/restock/adjust', { ...op, delta: 1.5, requestId: randomUUID() }, 400);
  await call('/restock/adjust', { ...op, location: 'ARMAZEM', delta: -2, requestId: randomUUID() });
  assert.equal((await prisma.product.findUnique({ where: { id: a.id } })).stockArmazem, 5);
  pass('reposição por local, reenvio idempotente e bloqueio de estoque negativo');
  await Promise.all([call('/restock/adjust', { ...op, delta: 1, requestId: randomUUID() }), call('/restock/adjust', { ...op, delta: 1, requestId: randomUUID() })]);
  assert.equal((await prisma.product.findUnique({ where: { id: a.id } })).stockLoja, 7);
  pass('ajustes simultâneos preservam ambas as entradas');
  const s2 = await call('/inventory', {}, 201);
  const countBody = { productId: a.id, mode: 'SET', quantity: 6, requestId: randomUUID() };
  await call(`/inventory/${s2.id}/count`, countBody);
  const oldReview = await call(`/inventory/${s2.id}/review`);
  await call(`/inventory/${s2.id}/count`, { ...countBody, quantity: 5, requestId: randomUUID() });
  await call(`/inventory/${s2.id}/finalize`, { reviewToken: oldReview.reviewToken }, 409);
  await call('/restock/adjust', { ...op, delta: -1, requestId: randomUUID() });
  const conflicting = await call(`/inventory/${s2.id}/review`); assert.equal(conflicting.summary.conflicts, 1);
  await call(`/inventory/${s2.id}/finalize`, { reviewToken: conflicting.reviewToken }, 409);
  const newProduct = await create('Nova peça', 2, 0); assert.equal((await call(`/inventory/${s2.id}/review`)).summary.conflicts, 2);
  await call(`/inventory/${s2.id}/recount`, { productId: a.id });
  await call(`/inventory/${s2.id}/recount`, { productId: newProduct.id });
  await call(`/inventory/${s2.id}/count`, { ...countBody, quantity: 5, requestId: randomUUID() });
  await call(`/inventory/${s2.id}/count`, { ...countBody, productId: newProduct.id, quantity: 2, requestId: randomUUID() });
  const refreshed = await call(`/inventory/${s2.id}/review`); assert.equal(refreshed.summary.conflicts, 0);
  await call(`/inventory/${s2.id}/finalize`, { reviewToken: refreshed.reviewToken });
  pass('revisão desatualizada é recusada; alterações e novos produtos exigem recontagem');
  const empty = await call('/inventory', {}, 201); const emptyReview = await call(`/inventory/${empty.id}/review`);
  await call(`/inventory/${empty.id}/finalize`, { reviewToken: emptyReview.reviewToken }, 400);
  await call(`/inventory/${empty.id}/cancel`, {});
  assert.equal(await prisma.stockMovement.count({ where: { reference: empty.id } }), 0);
  pass('contagem vazia exige confirmação explícita e cancelamento não altera estoque');
  // O teste de busca usa vetores sintéticos e transporte stub; nenhum provedor é cobrado.
  const size = await prisma.size.upsert({ where: { name: 'QA M' }, update: {}, create: { name: 'QA M', code: '97' } });
  const pattern = await prisma.pattern.upsert({ where: { name: 'Estampa QA' }, update: {}, create: { name: 'Estampa QA', code: '9997' } });
  const indexed = await prisma.product.update({ where: { id: a.id }, data: { patternId: pattern.id, sizeId: size.id } });
  const variant = await prisma.product.update({ where: { id: b.id }, data: { patternId: pattern.id } });
  const image = await prisma.productImage.create({ data: { productId: indexed.id, type: 'ROUPA', url: '/uploads/products/test.png', data: Buffer.from('test') } });
  require('../dist/config/vector-database').vectorDatabase = () => ({ $queryRaw: async () => [{ productImageId: image.id, score: 0.95 }] });
  require('../dist/services/product-image-embedding.service').ensureVisualSearchSetup = async () => {};
  process.env.OPENROUTER_API_KEY = 'local-test-only';
  global.fetch = async (url, options) => {
    assert.equal(url, 'https://openrouter.ai/api/v1/embeddings');
    const payload = JSON.parse(options.body); assert.equal(payload.dimensions, 768); assert.equal(payload.input[0].content[0].type, 'image_url');
    return new Response(JSON.stringify({ data: [{ embedding: Array(768).fill(0.1) }] }), { status: 200 });
  };
  const form = new FormData(); const png = await require('sharp')({ create: { width: 4, height: 4, channels: 3, background: '#ff0080' } }).png().toBuffer();
  form.append('images', new Blob([png], { type: 'image/png' }), 'qa.png');
  const visual = await nativeFetch(base + '/restock/search', { method: 'POST', headers: { Authorization: 'Bearer ' + token }, body: form });
  const results = await visual.json(); assert.equal(visual.status, 200, JSON.stringify(results));
  assert.ok(results.matches.some((m) => m.product.id === indexed.id)); assert.ok(results.matches.some((m) => m.product.id === variant.id));
  assert.ok(results.matches.every((m) => m.product.images.every((i) => !('data' in i))));
  pass('busca vetorial consulta banco separado, retorna variantes e não transfere binários');
  console.log(`${passed} cenários de integração aprovados.`);
}
main().catch((error) => { console.error(error); process.exitCode = 1; }).finally(async () => { global.fetch = nativeFetch; if (server) server.close(); await prisma.$disconnect(); });
